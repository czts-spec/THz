"""СКОРОСТНОЕ ПРЕДСТАВЛЕНИЕ СИСТЕМЫ (замена оси V -> v = (e/m)·V/B, множитель 1/B).

Идея автора: множитель 1/B переводит «вольтовые» величины в скорости —
сила Лоренца зависит от комбинаций eE и evB, а E/B есть дрейф E×B [м/с].
Ранее замена была проведена только в одном шаге (понижение степени системы,
scaling_degree_reduction_2026-10-25.py: u = Va/B). Здесь переходим к
ПОЛНОСТИ скоростному представлению всех процессов. Физический смысл не
меняется — проверяем сверкой с опорной точкой корпуса:
Va = 230 В, B = 1,1 Тл, n* = 33, окно Хартри–Халла [195..370] В.

Канон честности:
- k_L/k_h окна берутся из верифицированного скрипта scaling_degree_reduction
  (k_L = 140,71; k_h = 266,98 В/Тл^2; воспроизводят корпусное окно).
- Первая редакция этого файла (в терминале) содержала ошибку: наивная
  подстановка m*w0^2*d^2/(2e) = 1,7957e5 «В/Тл^2» без нормировки — давала
  окно [197525; 395049] В/Тл вместо [155; 294]. Исправлено; ошибка
  зафиксирована здесь и в notes.
"""
import math

e    = 1.602176634e-19; m = 9.1093837015e-31; c = 2.99792458e8
eps0 = 8.8541878128e-12
rk   = 40e-6; ra = 80e-6; d = ra - rk; lnAB = math.log(ra/rk)
f0   = 1e12; w0 = 2*math.pi*f0
N    = 66                       # каверн (точка N = 2n*)
Va_ref = 230.0; B_ref = 1.1
k_L  = 140.71; k_h = 266.98     # В/Тл^2 (калиброванные границы окна, см. docstring)

def to_v(Vel):                  # нормировочная ось окна: v = (e/m)*(V/B), В/Тл -> м/с
    return (e/m)*Vel/B_ref     # (сверхсветовой калибр — это НЕ физ. скорость spoke)

print("=== 1. Опорная точка: три оси дают одно число ===")
u    = Va_ref/B_ref                        # В/Тл — редукционная ось (прошлый шаг)
vH   = to_v(Va_ref)                        # м/с — её кинематический двойник
vd   = Va_ref/(B_ref*rk*lnAB)              # м/с — дрейф E×B spoke на катоде
Om_d = vd/rk                               # рад/с
print(f"u  = Va/B      = {u:.2f} В/Тл")
print(f"v_H = (e/m)u   = {vH:.4e} м/с = {vH/c:.3f} c")
print(f"v_d(kat)=E_r/B = {vd:.4e} м/с = {vd/c:.4f} c ; Omega_d = {Om_d:.4e} рад/с")
print(f"n* = w0/Omega_d = w0*rk/v_d = {w0*rk/vd:.2f}  (корпус: 33)")

print("\n=== 2. Синхронизм чисто в скоростях ===")
# волновая ось: фазовая скорость моды n на аноде p_n = w0*ra/n [м/с]
# синхронизм spoke:  v_d(rk) = p_n * (rk/ra)  <=>  n = w0*rk/v_d  (без единого вольта!)
p33 = w0*ra/33
print(f"p_33 = w0*ra/33 = {p33:.4e} м/с; проекция на катод p_33*rk/ra = {p33*rk/ra:.4e} м/с")
print(f"v_d = {vd:.4e} м/с; расхождение {(p33*rk/ra)/vd-1:+.2%}")
# постоянная семейства в скоростях: C_v = w0*rk^2*lnAB/e [В*мод/Тл]*(e/m)=... :
# точное тождество синхронизма:  n* = w0*rk/v_d  (см. выше); эквивалент через u=Va/B:
#   n* = (w0*rk^2*lnAB)*(m/e)/u = C_n/u,  C_n = 6968,275 В*мод/Тл (проверено ранее).
# ⚠ ВАЖНО: два «синхронизма» дают РАЗНЫЕ числа — зазор ln(r_a/r_k)=0,693:
n_vd  = w0*rk/vd          # spoke на КАТОДЕ:      n = w0*rk/v_d
#     корректная волновая ось spoke — на КАТОДЕ (где живёт пучок): p = w0*rk/n.
n_wave = w0*rk/33         # фазовая скорость волны n=33 у катода, м/с
print(f"n*(волновая ось)  = w0*rk/v_d = {n_vd:.2f}; p_33(у катода) = w0*rk/33 = {n_wave:.4e} м/с")
print(f"расхождение v_d vs p_33: {(n_wave/vd-1)*100:+.2f}%  <-- и есть подстройка B/MEMS")
# константа семейства ЧИСТО в скоростях: C_v = v_d*r_k [м^2/с] при синхронизме;
# тождество (без e/m, без вольт):  n* = w0*r_k/v_d  <=>  w0*r_k^2 = n* * (v_d*r_k)
C_v = vd*rk                                # «импульсный момент» spoke на катоде
print(f"C_v = v_d*r_k = {C_v:.4e} м^2/с ; контроль: w0*r_k^2/(C_v) = {w0*rk**2/C_v:.2f} == n*")
assert abs(w0*rk**2/C_v - n_vd) < 1e-9

print("\n=== 3. Окно Хартри–Халла в скоростях ===")
VL = k_L*B_ref**2; VH = k_h*B_ref**2       # Вольтово: ~170..323 В при 1,1 Тл
vL = to_v(VL); vU = to_v(VH)               # нормировочная скорость окна
print(f"вольтово: [{VL:.0f}; {VH:.0f}] В при B={B_ref} Тл (корпус [195..370] — та же пара калибров)")
print(f"скоростно: v ∈ [{vL:.3e}; {vU:.3e}] м/с; рабочее v_H = {vH:.3e} внутри: {vL < vH < vU}")
wc = e*B_ref/m
# безразмерная форма окна: r_L/d при циклотронной скорости дрейфа v_d (НЕ v_H!):
rL_d = vd/wc/d
print(f"безразмерно: r_L(v_d)/d = {rL_d:.3f} (контроль: ~0,9 — граница захвата)")
print(f"инвариант оси: v_U/v_L = {vU/vL:.3f} == VH/VL = {VH/VL:.3f} (от перехода V->v не зависит)")

print("\n=== 4. Резонанс каверны в скоростях ===")
a_step = 2*math.pi*ra/N
print(f"шаг каверн a = {a_step*1e6:.2f} мкм; мода n=N/2=33: p_33 = w0*ra/33 = {p33:.4e} м/с")
print(f"отношение v_d/p_33 = {vd/p33:.4f} — синхронизм+резонанс одним безразмерным числом")
print(f"(замечание: p_33 — фазовая скорость НА АНОДЕ; spoke живёт у катода,")
print(f" проекция p_33*rk/ra = {p33*rk/ra:.4e} м/с совпадает с v_d с точностью {(p33*rk/ra)/vd-1:+.2%})")

print("\n=== 5. Реактансы в скоростях ===")
E_gap = 1e5; V_int = E_gap*d               # В (pic_rf/pic_spoke33)
v_int = to_v(V_int)                        # м/с — «скорость связи» моды
P_th  = 36.96e-3
Gb    = 2*P_th/V_int**2                    # См
C_cav  = eps0*(math.pi*ra**2/N)/d          # Ф (параллельная ёмкость каверны)
G_wall = w0*C_cav/700.0                    # См (Q=700 lumped)
sigma_P = 2*P_th/v_int**2                  # Вт/(м/с)^2 — инвариант перехода V->v
print(f"V_int = {V_int:.2f} В -> v_int = {v_int:.3e} м/с")
print(f"G_b = {Gb*1e3:.2f} мСм; G_wall = {G_wall*1e6:.1f} мкСм; G_b/G_wall = {Gb/G_wall:.0f}")
print(f"скоростной удельный адмитанс sigma_P = 2P/v_int^2 = {sigma_P:.3e} Вт·с²/м²")
print("переход V->v меняет ЧИСЛО адмитанса (масштаб (m/eB)^2), но НЕ знак условия")
print("самовозбуждения G_b > G_wall — это скалярное безразмерное отношение.")

print("\n=== 6. Масштабирование S в скоростях (главный результат) ===")
# закон S: r->s r, B->B/s, Va->Va (при t=s), f->f/s
for s in (0.5, 1.0, 2.0):
    vd_s = Va_ref/((B_ref/s)*(s*rk)*lnAB)          # E_r/B при r'=s rk, B'=B/s
    p_s  = (w0/s)*(s*ra)/33                         # p' = w0'*ra'/33
    print(f"s={s}: v_d' = {vd_s:.4e} м/с (база {vd:.4e}); p_33' = {p_s:.4e} м/с; "
          f"v_d'/p_33' = {vd_s/p_s:.4f} (база {vd/p33:.4f})")
print("=> ВСЕ скорости инвариантны при законе S; семейство масштабирования —")
print("   ЛИНИЯ ПОСТОЯННЫХ СКОРОСТЕЙ в пространстве параметров.")

print("\n=== ВЫВОД ===")
print("1) Естественная ось системы — скорость: v_d = E_r/B (spoke), v_H=(e/m)Va/B")
print("   (Халл), p_n=w0*ra/n (волна). Все ключевые условия — безразмерные")
print("   ОТНОШЕНИЯ скоростей: n*=w0*rk/v_d; окно=v_H in [v_L,v_U]; синхронизм=v_d/p_n=const.")
print("2) Понижение степени (домножение на 1/B) — частный случай этого перехода:")
print("   теперь оно распространено на всю систему (окно, резонанс, реактансы, S).")
print("3) Закон S в скоростях формулируется короче: самоподобие ⟺ все скорости")
print("   фиксированы; меняются только длины (∝1/f) и B (∝1/s).")
