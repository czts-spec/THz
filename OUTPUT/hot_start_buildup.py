#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Горячий старт микромагнетрона: характерное время выхода на режим генерации.

Постановка (по замечанию автора 2026-10-25): тепловая нагрузка элемента
150x150 мкм ~ 17 мВт, dT~13 К -> "холодный" старт не является ограничителем;
реальный сценарий включения — горячий: напряжение V_a и поле B подаются
практически мгновенно (ps-ns коммутация), пучок эмиссии появляется сразу
(плёночный Sc-катод, вторичная эмиссия, SCI Q1). Тогда вопрос сводится к
времени НАРАСТАНИЯ СВЯЗАННОЙ МОДЫ из шума: t_build = T_dec * ln(A_ss/A_noise).

Метод [вычислено здесь]: цепная модель Van der Pol (классический подход
в магнетронной теории, ср. Hutchinson ch.15 / Нусинович) + числа корпуса:
  G_b/G_wall (reactance_correction.py, три края V_int);
  R_sh, C_cell, N=66, f0=1 ТГц, Q=700 (SCI Q4);
  шумовой затравочный уровень kTB через мощность потерь стенки.
Всё аналитически, без PIC-итераций (просьба автора).
"""
import math

kB = 1.380649e-23
eps0 = 8.8541878128e-12; mu0 = 4*math.pi*1e-7
f0 = 1e12; w0 = 2*math.pi*f0
Va = 230.0; rk = 40e-6; ra = 80e-6; d = ra-rk
N = 66; Q = 700.0
C_cell = eps0*(math.pi*ra**2/N)/d
R_sh = Q/(w0*C_cell)          # сопротивление связи одной каверны
G_wall = N/R_sh               # суммарные стеночные потери блока
P_th_per_uA_eV = 154.0      # мкВт на мкА при съёме 154 эВ/э (pic_spoke33):
                            # 1 мкА * 154 эВ = 154 мкВт; размерность держим явно.

def buildup(Vint, Ib_uA, T_phys_K=300.0, tag=""):
    """t_build по Ван дер Полю: dA/dt = A/Tdec*(1 - A^2/Ass^2)."""
    P = Ib_uA*P_th_per_uA_eV*1e-6            # Вт = мкА * 154 мкВт/мкА
    Gb = 2*P/Vint**2                          # активная проводимость пучка
    ratio = Gb/G_wall
    if ratio <= 1:
        print(f"{tag} V_int={Vint:.1f} В, Ib={Ib_uA} мкА: Gb/Gwall={ratio:.3f} <= 1 -- НЕЗАПУСК")
        return None
    Tdec = 2*Q/w0                             # декремента времени (ln e за Tdec)
    Ass2 = P/(ratio-1.0)                       # стационарная мощность моды
    A_noise = kB*T_phys_K*f0                  # доступная шумовая мощность kTB
    n = math.sqrt(Ass2/A_noise)                # отношение амплитуд SS/шум
    t_lin = Tdec*math.log(n)                   # линейный участок (экспонента)
    t_sat = Tdec*math.log(2)                   # насыщение до 1/e от SS (логистика)
    t_tot = t_lin + t_sat
    print(f"{tag} V_int={Vint:6.1f} В  Ib={Ib_uA:5.1f} мкА | Gb/Gwall={ratio:8.1f} "
          f"Tdec={Tdec*1e12:5.1f} пс | P_ss={Ass2*1e3:8.2f} мВт | n=SS/noise={n:6.1e} "
          f"| t_build={t_tot*1e9:7.2f} нс ({t_tot*f0:6.0f} периодов)")
    return t_tot

print("=== ПАРАМЕТРЫ БЛОКА ===")
print(f"C_cell={C_cell*1e15:.2f} фФ  R_sh={R_sh/1e3:.1f} кОм  G_wall={G_wall*1e6:.1f} мкСм  Tdec=2Q/w0={2*Q/w0*1e12:.1f} пс")

print("\n=== СВОДНАЯ ТАБЛИЦА ГОРЯЧЕГО СТАРТА (три края V_int из reactance_correction) ===")
for name,Vx in (("консерв.", math.sqrt(Va*4.0)), ("оптимист", 4.0)):
    for IuA in (20.0, 100.0, 1000.0):
        buildup(Vx, IuA, tag=f"[{name:9s}]")
# нижний край V_int=Va: Gb<Gwall при любом Ib<=1 мА -- уже известно (f9d8357), пропускаем

print("\n=== ТЕПЛОВОЙ КОНТРОЛЬ 'горячести' старта (правило квадрат-куб, thermal_vacuum_notes) ===")
P_el = 17e-3            # Вт на элемент 150x150 мкм [в корпусе]
alpha_Cu = 1.11e-4      # м^2/с диффузия тепла в Cu
tau_th = d**2/alpha_Cu
# тепловая постоянная ПЛАНКИ элемента a=150 мкм (не зазора!): tau ~ a^2/alpha
a_el = 150e-6
tau_planck = a_el**2/alpha_Cu
print(f"зазор:   tau_th = d^2/alpha_Cu = {tau_th*1e9:.1f} нс")
print(f"планка 150 мкм: tau = a^2/alpha_Cu = {tau_planck*1e6:.1f} мкс "
      f"(это и есть тепловая инерция элемента; оценка через d была неверной осью)")
print("ВЫВОД: t_build ~ 1,4-1,9 нс << tau_th (14,4 нс зазор / 203 мкс планка) -> старт")
print("термически 'мгновенный': тепловая инерция НЕ влияет на время выхода на режим;")
print("установившийся dT~13 К [в корпусе] приходит позже, в течение сотен мкс, не мешая генерации.")
