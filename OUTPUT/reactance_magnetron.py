#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Реактанс (импеданс/адмитанс) микромагнетрона ТГц и согласованная нагрузка.

Параметризация раскрыва: свободное пространство = предельный случай рупора
(раскрытие 180°), поэтому считаем единую параметризацию через коэффициент
использования раскрыва k_u и телесный угол.

Рабочая точка [в корпусе, синхронизирована в scaling_degree_reduction]:
  f0 = 1 ТГц, N = 66 каверн, n* = 33 spoke-мода, V_a = 230 В, B = 1,1 Тл,
  r_k = 40 мкм, r_a = 80 мкм, d = зазор 40 мкм, заявка P_вых = 0,5 Вт (П-2).

Метод [вычислено здесь]:
  1. Проводимость пучка на основной гармонике spoke G_b = I_b*dW/dV (lumped,
     по аналогии с магнетронной теорией Ваннека/Нусиновича для бегущей волны).
  2. Потери стенки: каждая каверна — резонатор с Q; эквивалентное
     сопротивление потерь R_wall = omega*L_cav/Q (для параллельного контура
     R_p = Q/(omega*C) = omega*L*Q... аккуратнее: для RLC-цепи,
     представляющей каверну, характеристическое сопротивление волновода
     анодного блока Z_wv = eta0*(d/a)^1/2... )
     Берём консервативную оценку: R_sh от добротности объёмной модели
     R_sh = Q * omega * mu0 * V_cav / (A_eff^2 / V_cav) ... используем
     стандартную формулу шунтового сопротивления резонатора
     R_sh = Q/(omega*C_eq), C_eq из ёмкости зазора.
  3. Нагрузка: волновод/рупор с волновым сопротивлением Z_L = eta0/sqrt(1-(fc/f)^2)
     для прямоугольного волновода TE10;Eta_free = 376,73 Ом (своб. пространство).
  4. Согласование: трансформатор (E-plane step / iris) + расчёт КСХ.

Всё выводится численно; никаких сеточных PIC — только аналитика по корпусным
формулам (канон: перед объявлением нового знания сверяться с OUTPUT).
"""
import math

# --- константы и рабочая точка ---
e   = 1.602176634e-19      # Кл
m_e = 9.1093837015e-31     # кг
mu0 = 4*math.pi*1e-7       # Гн/м
eps0 = 8.8541878128e-12    # Ф/м
eta0 = math.sqrt(mu0/eps0) # ~376.73 Ом

f0   = 1.0e12              # Гц
w0   = 2*math.pi*f0
N    = 66                  # каверн
nsp  = 33                  # spoke-мода
Va   = 230.0               # В
B    = 1.1                 # Тл
rk   = 40e-6               # м
ra   = 80e-6               # м
d    = ra - rk             # 40 мкм зазор
Pout = 0.5                 # Вт (заявка П-2)
Qcav = 700.0               # заявка корпуса (claim Q~700)
Ib_th = 240e-6             # A, порог самозапуска из pic_spoke33
Ib_nom= 20e-6              # A, заявленный стартовый ток

print("=== РЕАКТАНС МИКРОМАГНЕТРОНА (точка N=66/n*=33) ===")
print(f"eta0 = {eta0:.2f} Ом (свободное пространство = рупор 180 grad)")

# --- 1. проводимость пучка на spoke-гармонике ---
# Съём энергии из pic_spoke33: 154 эВ/э при E0=1e5 В/м (tормозящая дуга).
# Дифференциальная проводимость пучка G_b = dP/d(Va_gap^2)...
# Стандартная оценка для O-type/M-type: активная составляющая admittance пучка
# Y_b = G_b - j*B_b, G_b ~ -(2*Pbeam)/(Vint^2) где Vint - эффективное
# напряжение взаимодействия (часть Va, снятая spoke-полем).
dW_ev = 154.0                    # эВ/э съём (pic_spoke33 notes)
Pbeam_unit = Ib_th * dW_ev       # Вт при пороговом токе (макс съём)
Pbeam_nom  = Ib_nom  * dW_ev      # Вт при номинальном 20 мкА
# Эффективное напряжение взаимодействия: поле E0*r_k*ln(ra/rk)*F_mod,
# F_mod - фактор перекрытия spoke с диодом (~1 по pic_spoke33 т.к. вся энергия съедается)
Vint = math.sqrt(Pbeam_unit*abs(Y := 0)) if False else None
# проще: G_b = 2*P/Vint^2 c Vint = Va*sin(pi/n*)*lnAB... возьмём Vint = Va/n*? 
# Физически корректная lumped-оценка: мода "видит" напряжение Va между катодом и
# анодом, spoke разбивает на n* сегментов -> Vint ~ Va (полное) с фазой psi*.
Vint = Va
G_b = 2*Pbeam_unit/Vint**2       # См
Y_b = complex(-G_b, 0.0)         # отрицательная проводимость = отдача энергии
print(f"P_beam(threshold)={Pbeam_unit*1e3:.2f} mW, P_beam(nominal 20uA)={Pbeam_nom*1e3:.3f} mW")
print(f"G_b (admittance пучка, spoke) = {G_b*1e6:.3f} uS  (отрицательная => усиление)")

# --- 2. шунтовое сопротивление потерь анодного блока ---
# Эквивалент: N каверн || ; одна каверна = LC-резонатор.
# Ёмкость зазора на моду: C_gap ~ eps0*A_cell/d, A_cell = 2*pi*ra/N * L_ax
L_ax = 200e-6  # длина аксиальная ячейки (по корпусу пластина 200 мкм)
A_cell = 2*math.pi*ra/N * L_ax
C_cell = eps0*A_cell/d
R_sh_cell = Qcav/(w0*C_cell)     # Ом, шунтовое одной каверны
R_sh_total = R_sh_cell/N          # N параллельно
G_wall = 1/R_sh_total
print(f"C_cell={C_cell*1e15:.2f} fF, R_sh_cell={R_sh_cell:.3e} Ohm, R_sh(N=66)={R_sh_total:.3e} Ohm")
print(f"G_wall = {G_wall*1e6:.3f} uS")

# --- 3. индуктивная/ёмкостная реактивность входа ---
# Вход резонансной цепи: Y_in = G_wall + j*w*C_cell*N + Y_b + Y_load
X_cav = -1/(w0*C_cell*N)
print(f"реактивность блока X = {X_cav:.3e} Ом (ёмкостная)")

# --- 4. нагрузка: рупор/свободное пространство ---
# Волновое сопротивление TE10 волновода a x b (b=d): fc = c/(2a)
# Для ТГц раскрыв выбираем a так, чтобы fc << f0: a = 300 мкм -> fc=0,5 ТГц
a_wg = 300e-6
fc = 299792458.0/(2*a_wg)
Z_TE = eta0/math.sqrt(1-(fc/f0)**2)
print(f"волновод a={a_wg*1e6:.0f}um: fc={fc/1e12:.2f} TГц, Z_TE10={Z_TE:.1f} Ом")
# Свободное пространство (рупор 180 grad): Z = eta0/k_u, k_u~0.5..1
for ku in (0.5, 0.7, 0.9, 1.0):
    print(f"  раскрыв k_u={ku}: Z_ant={eta0/ku:.1f} Ом")

# --- 5. согласование и КПД ---
# Условие критической связи: G_load = G_wall + |G_b| (при генерации)
G_load_opt = abs(G_b) - G_wall if abs(G_b)>G_wall else None
if G_load_opt is None:
    print("ПРЕДУПРЕЖДЕНИЕ: |G_b| < G_wall -> самовозбуждения нет, нужен locking (см. pic_lock_grid)")
    G_load_opt = abs(G_b)  # режим вынужденной генерации: вся мощность в нагрузку
R_load_opt = 1/G_load_opt
# КПД внешняя связь: beta = G_load/G_wall... для генератора: eta_out = G_load/(G_load+G_wall)
beta = G_load_opt/G_wall
eta_out = G_load_opt/(G_load_opt+G_wall)
Pconv = Pbeam_unit  # доступная мощность пучка (threshold)
Pext  = Pconv*eta_out
print(f"оптимальная нагрузка R_L = {R_load_opt:.3e} Ом, beta={beta:.2f}, eta_out={eta_out:.3f}")
print(f"P внешняя (при Ib_th) = {Pext*1e3:.2f} mW; при Ib_nom = {Pext*Ib_nom/Ib_th*1e3:.3f} mW")

# КСХ относительно нагрузки рупора 377/ku
for ku,ZL in ((1.0,eta0),(0.7,eta0/0.7)):
    gamma = (ZL-R_load_opt)/(ZL+R_load_opt)
    vswr = (1+abs(gamma))/(1-abs(gamma)) if abs(gamma)<1 else float('inf')
    print(f"рупор k_u={ku}: Z_L={ZL:.1f} vs R_Lopt={R_load_opt:.2e} -> |Gamma|={abs(gamma):.4f}, VSWR={vswr:.2f}")
    print(f"   => нужен трансформатор (iris/E-step) с коэфф {math.sqrt(ZL/R_load_opt):.1f}")

print("\nИТОГ: см. OUTPUT/reactance_notes_2026-10-25.md")
