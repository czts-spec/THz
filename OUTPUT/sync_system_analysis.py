#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Система уравнений (а)+(б)+(в): аналитический критерий рабочей точки.
Оси происхождения: [вычислено здесь]; база формул — классическая теория
магнетрона (Hutchinson, Principles of Microwave Magnetrons, гл. 15–16)
[внешний источник]; геометрия/рабочая точка — концепт корпуса П-2 [в корпусе].

Ветви (неизвестные V_a, B, n_spoke, P_inj при фиксированных f0=1 ТГц и геометрии):
  (а) синхронизм spoke:   n* = ω0/Ω_d,  Ω_d = v_d/r_k,  v_d = V_a/(B·r_k·ln(r_a/r_k))
  (б) спайк-режим:        сгусток в ТОРМОЗЯЩЕЙ дуге поля: фаза ψ ∈ [π, 2π]
      + условие малости дефазировки за пролёт |Φ_tr| < π/2,
        Φ_tr = (ω0 − n·Ω_d)·τ_tr,  τ_tr = π/n/Ω_d (полусектор spoke)
  (в) injection locking:  |Δ| ≤ Ω_A·√(P_inj/P_st),  Ω_A = ω0/(2Q)  (формула Адлера)

КЛЮЧЕВОЕ НАБЛЮДЕНИЕ [вычислено здесь]: подстановка (а) в выражение Φ_tr даёт
Φ_tr(n=n*) ≡ π·(ω0/n* − Ω_d)/Ω_d → 0: синхронный spoke автоматически удовлетворяет
условию малости дефазировки; торможение задаётся фазовым сдвигом ψ сгустка
относительно волны (pic_rf R1: ψ*≈5,8 рад ∈ [π,2π] ✓). Значит (а) и (б) не
конкурируют, а дополняют друг друга; (в) после пересогласования резонатора на n*
сводится к MEMS-удержанию Δ ≤ диапазона подстройки. РЕШЕНИЕ ЕДИНОТОЧНО: n*≈33.
"""
import numpy as np

me, e, eps0, c = 9.1093837e-31, 1.602176634e-19, 8.8541878128e-12, 2.99792458e8

rk, ra = 40e-6, 80e-6          # геометрия корпуса [в корпусе]
N      = 128
neff   = N//2
f0     = 1.0e12
omega0 = 2*np.pi*f0
lnA    = np.log(ra/rk)
d      = ra - rk

vd    = lambda Va,B: Va/(B*rk*lnA)
Om    = lambda Va,B: vd(Va,B)/rk
nstar = lambda Va,B: omega0/Om(Va,B)
VL    = lambda B: me*(e*B/me)**2*d**2/(2*e)     # нижняя граница окна Халла

print("="*74); print("БЛОК 1. (а) Синхронизм разрешён по V_a(n*, B)"); print("="*74)
print("V_a(синхр) = ω0·B·r_k²·ln(r_a/r_k)/n*")
for n in [33, 34, 40, 64]:
    for B in [1.0, 1.1, 1.2]:
        Va = omega0*B*rk**2*lnA/n
        ok = "✓ в окне Халла" if VL(B)*0.9 <= Va else "✗ ниже порога запуска"
        print(f"  n*={n:>3}, B={B:.1f} Тл → V_a = {Va:6.1f} В | V_Larmor(min)={VL(B):6.1f} В → {ok}")
print("""Вывод Б1: (а) ЖИВА при n*≈33–34: V_a=225–232 В при 1,1 Тл совпадает с корпусным
  230 В с точностью ~1%. Для π-моды n=64 точка (а) мертва (119 В < 170 В).""")

print(); print("="*74); print("БЛОК 2. Число оборотов — ревизия корпусной формулировки"); print("="*74)
Va_ref, B_ref = 230., 1.1
fc = e*B_ref/me/2/np.pi
print(f"f_c = {fc/1e9:.1f} ГГц; ларморовских оборотов ЭЛЕКТРОНА за период волны T0: {fc/f0:.3f}")
print(f"витков spoke-обхода за T0: {Om(Va_ref,B_ref)/(2*np.pi*f0):.3f}; n* = {nstar(Va_ref,B_ref):.1f}")
print("⇒ «десятки оборотов на период волны» в корпусе = ДЕСЯТКИ СГУСТКОВ n*≈33,")
print("  а не оборотов одного электрона (те — доли). Уточнить формулировку концепта.")

print(); print("="*74); print("БЛОК 3. (б) Окно устойчивости по моде n из условия |Φ_tr| < π/2"); print("="*74)
print("τ_tr = π/n/Ω_d; Φ_tr = (ω0 − n·Ω_d)·τ_tr; тормозящая дуга сгустка ψ∈[π,2π] — отдельное")
print("условие (фаза эмиссии/захвата), здесь — усреднение поля за пролёт:")
ns = np.arange(16, 65)
taus = np.pi/ns/Om(Va_ref,B_ref)
Phis = (omega0 - ns*Om(Va_ref,B_ref))*taus
good = ns[np.abs(Phis) < np.pi/2]
print(f"  допустимый диапазон: n ∈ [{good.min()}; {good.max()}] (широко!)")
for n in [20,24,28,33,40,48,56,64]:
    tau = np.pi/n/Om(Va_ref,B_ref)
    Phi = (omega0 - n*Om(Va_ref,B_ref))*tau
    tag = "✓" if abs(Phi)<np.pi/2 else ("погранично" if abs(Phi)<np.pi else "✗ усреднение")
    print(f"  n={n:>3}: τ_tr={tau*1e12:5.2f} пс, Φ_tr={Phi:+6.2f} рад → {tag}")
print("""Вывод Б3: решение (а) n*=33.3 лежит глубоко внутри окна устойчивости.
  Отрицательный pic_grid V1/V4 объясняется НЕ механизмом, а стартом без spoke-структуры
  (равномерное облако не имеет ψ∈[π,2π]) и тем, что тестировалась только π-мода.""")

print(); print("="*74); print("БЛОК 4. (в) Injection locking: Адлер после пересогласования n"); print("="*74)
Q = 700.; OA = omega0/Q/2
D64 = abs(omega0 - neff*Om(Va_ref,B_ref)); D33 = abs(omega0 - 33*Om(Va_ref,B_ref))
Veff = np.pi*(ra**2-rk**2)*1e-3
Pst  = omega0*0.5*eps0*(1e5)**2*Veff/Q
print(f"Ω_A/2π = {OA/2/np.pi/1e9:.2f} ГГц (Q={Q:.0f}); MEMS-диапазон подстройки ±23 ГГц (Q5)")
print(f"π-мода n=64: Δ/2π = {D64/2/np.pi/1e9:6.0f} ГГц ⇒ P_inj ≥ P_st·(Δ/Ω_A)² = "
      f"{Pst*(D64/OA)**2:.0f} Вт — НЕВЫПОЛНИМО")
print(f"мода n*=33:  Δ/2π = {D33/2/np.pi/1e9:6.1f} ГГц ⇒ то же условие даёт "
      f"P_inj ≥ {Pst*(D33/OA)**2*1e3:.0f} мВт/каверну — тоже много для инжекции;")
print("""  ⟵ честная трактовка: Δ=9,8 ГГц покрывается MEMS-подстройкой ±23 ГГц БЕЗ внешней
     инжекции; роль ветви (в) = удержание настройки и фазовая стабилизация (затравка
     ≳P_st=6 мВт/каверну уже достаточна при Δ→0 после юстировки). Самозапуск тогда
     определяется порогом тока эмиссии (Buneman-порог по полю E_th~ω0·m·r_k/e≪E_раб),
     PIC-прогон со spoke n=33 даст I_b,th — следующий шаг, закрывает SCI Q6.""")

print(); print("="*74); print("БЛОК 5. РЕШЕНИЕ СИСТЕМЫ — единая рабочая точка"); print("="*74)
print(f"""
[вычислено здесь] Система (а)+(б)+(в) РАЗРЕШИМА, решение единственно с точностью ±1 мода:
  B = 1,1 Тл;  V_a = 230 В (окно Халла [195;~370] ✓);  f0 = 1 ТГц;
  n* = ω0/Ω_d = {nstar(230,1.1):.1f} → spoke из 33 сгустков, угловой шаг 2π/33 = {2*np.pi/33:.3f} рад,
       линейный шаг на аноде 2πr_a/33 = {2*np.pi*ra/33*1e6:.2f} мкм;
  (а) задаёт n*; (б) выполнено: n* в окне устойчивости + ψ∈[π,2π] выбирается захватом;
  (в) сводится к MEMS-удержанию Δ≤23 ГГц ✓ (для π-моды было ✗ — 920 ГГц).
РЕКОМЕНДАЦИЯ КОНЦЕПТУ: заменить «π-моду N/2=64» на «сповую моду синхронизма n*≈33»;
  каверны — 66 (=2·33, субгармоническое согласование) или оставить 64 с проверкой
  симметрии отдельным прогоном. ВСЕ ТРИ ВЕТВИ ВЫЖИЛИ, ОБЪЕДИНИВСЬ В ОДНУ ТОЧКУ.""")
